function renderWorkspaceFilesTable() {
  const tbody = document.getElementById('ws-files-tbody');
  const countBadge = document.getElementById('ws-files-count');
  if (countBadge) countBadge.innerText = `${workspaceFilesList.length} Files`;

  if (workspaceFilesList.length === 0) {
    tbody.innerHTML = '<tr><td colspan="4" class="text-center py-6 text-muted">No files in ./workspace directory yet.</td></tr>';
    return;
  }

  tbody.innerHTML = workspaceFilesList.map(f => {
    const sizeKb = (f.size_bytes / 1024).toFixed(1);
    const dateStr = new Date(f.modified_time * 1000).toLocaleString();
    return `
      <tr>
        <td><strong>📄 <code>${escapeHtml(f.filename)}</code></strong></td>
        <td><span class="text-secondary text-sm">${sizeKb} KB</span></td>
        <td><span class="text-muted text-sm">${dateStr}</span></td>
        <td>
          <button class="btn btn-secondary btn-sm" onclick="openWorkspaceFile('${escapeHtml(f.filename)}')">
            ✏️ View / Edit
          </button>
          <button class="btn btn-secondary btn-sm" onclick="deleteWorkspaceFile('${escapeHtml(f.filename)}')">
            🗑️
          </button>
        </td>
      </tr>
    `;
  }).join('');
}

async function openWorkspaceFile(filename) {
  try {
    const res = await fetch(`/api/workspace/files/${encodeURIComponent(filename)}`);
    if (res.ok) {
      const data = await res.json();
      activeWorkspaceFile = data.filename;
      document.getElementById('ws-active-filename').value = data.filename;
      document.getElementById('ws-editor-title').innerText = `📄 Editing: ${data.filename}`;
      document.getElementById('ws-editor-placeholder').style.display = 'none';
      
      const textarea = document.getElementById('ws-editor-textarea');
      textarea.style.display = 'block';
      textarea.value = data.content;

      document.getElementById('ws-save-btn').style.display = 'inline-block';
      document.getElementById('ws-download-btn').style.display = 'inline-block';
    }
  } catch (e) {
    alert('Failed to read file: ' + e.message);
  }
}

async function saveActiveWorkspaceFile() {
  const filename = document.getElementById('ws-active-filename').value;
  const content = document.getElementById('ws-editor-textarea').value;
  if (!filename) return;

  try {
    const res = await fetch('/api/workspace/files', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ filename, content })
    });
    if (res.ok) {
      alert(`File '${filename}' saved successfully.`);
      fetchWorkspaceFiles();
    }
  } catch (e) {
    alert('Failed to save file: ' + e.message);
  }
}

function downloadActiveWorkspaceFile() {
  const filename = document.getElementById('ws-active-filename').value || 'file.txt';
  const content = document.getElementById('ws-editor-textarea').value;
  const blob = new Blob([content], { type: 'text/plain' });
  const a = document.createElement('a');
  a.href = URL.createObjectURL(blob);
  a.download = filename;
  a.click();
}

async function createNewWorkspaceFilePrompt() {
  const filename = prompt('Enter new filename (e.g. itinerary.txt, party_plan.md):');
  if (!filename || !filename.trim()) return;

  try {
    await fetch('/api/workspace/files', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ filename: filename.trim(), content: `# ${filename.trim()}\n` })
    });
    await fetchWorkspaceFiles();
    openWorkspaceFile(filename.trim());
  } catch (e) {
    alert('Error creating file: ' + e.message);
  }
}

async function deleteWorkspaceFile(filename) {
  if (!confirm(`Delete file '${filename}'?`)) return;
  try {
    const res = await fetch(`/api/workspace/files/${encodeURIComponent(filename)}`, { method: 'DELETE' });
    if (res.ok) {
      if (activeWorkspaceFile === filename) {
        document.getElementById('ws-editor-placeholder').style.display = 'block';
        document.getElementById('ws-editor-textarea').style.display = 'none';
        document.getElementById('ws-save-btn').style.display = 'none';
        document.getElementById('ws-download-btn').style.display = 'none';
        document.getElementById('ws-editor-title').innerText = '📄 File Editor';
      }
      fetchWorkspaceFiles();
    }
  } catch (e) {
    alert('Failed to delete file: ' + e.message);
  }
}

