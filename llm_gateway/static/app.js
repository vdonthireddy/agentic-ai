function renderBotResponse(data) {
  const container = document.getElementById('chat-messages-container');
  const div = document.createElement('div');
  div.className = 'chat-message message-bot';

  let toolsHtml = '';
  if (data.tool_calls && data.tool_calls.length > 0) {
    toolsHtml = `<div class="tool-call-feed">`;
    for (const tc of data.tool_calls) {
      const toolName = tc.tool || tc.name || 'tool';
      const argsStr = JSON.stringify(tc.args || {}, null, 2);
      const resPreview = tc.result_preview || (typeof tc.result === 'string' ? tc.result : JSON.stringify(tc.result || {}));
      toolsHtml += `
        <div class="tool-call-bubble">
          <div class="tool-call-header">
            <span>🛠️ Executed Tool: <strong>${escapeHtml(toolName)}</strong></span>
          </div>
          <div class="tool-call-detail">
            <code>${escapeHtml(argsStr)}</code>
            <div class="tool-output-preview">↳ ${escapeHtml(resPreview.substring(0, 160))}...</div>
          </div>
        </div>
      `;
    }
    toolsHtml += `</div>`;
  }

  let contentHtml = formatMarkdown(data.response || 'No response returned.');

  div.innerHTML = `
    <div class="message-bubble">
      ${toolsHtml}
      <div class="message-content">${contentHtml}</div>
    </div>
  `;
  container.appendChild(div);
  chatHistory.push({ role: 'assistant', content: data.response, tool_calls: data.tool_calls, timestamp: new Date().toISOString() });
}

