function populateSandboxToolSelect() {
  const sel = document.getElementById('sandbox-tool-select');
  if (!sel) return;
  sel.innerHTML = registeredToolsList.map(t => `
    <option value="${t.name}">${t.name} (${t.category})</option>
  `).join('');
  onSandboxToolSelect();
}

function onSandboxToolSelect() {
  const toolName = document.getElementById('sandbox-tool-select').value;
  const tool = registeredToolsList.find(t => t.name === toolName);
  const argsBox = document.getElementById('sandbox-args-json');

  if (tool && tool.params && tool.params.length > 0) {
    const exampleArgs = {};
    for (const p of tool.params) {
      exampleArgs[p.name] = p.example !== undefined ? p.example : '';
    }
    argsBox.value = JSON.stringify(exampleArgs, null, 2);
  } else {
    argsBox.value = '{}';
  }
}

function loadToolIntoSandbox(toolName) {
  const sel = document.getElementById('sandbox-tool-select');
  if (sel) {
    sel.value = toolName;
    onSandboxToolSelect();
  }
  document.getElementById('sandbox-tool-select').scrollIntoView({ behavior: 'smooth' });
}

async function executeToolSandbox() {
  const toolName = document.getElementById('sandbox-tool-select').value;
  const argsStr = document.getElementById('sandbox-args-json').value.trim();
  const runBtn = document.getElementById('sandbox-run-btn');
  const resultContainer = document.getElementById('sandbox-result-container');
  const resultBox = document.getElementById('sandbox-result-box');
  const latencyBadge = document.getElementById('sandbox-latency-badge');

  let argsObj = {};
  if (argsStr) {
    try {
      argsObj = JSON.parse(argsStr);
    } catch (e) {
      alert('Invalid JSON in arguments box: ' + e.message);
      return;
    }
  }

  runBtn.disabled = true;
  runBtn.innerHTML = '<span>⏳ Executing Tool...</span>';

  try {
    const res = await fetch('/api/tools/execute', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ tool: toolName, args: argsObj })
    });

    const data = await res.json();
    resultContainer.style.display = 'block';
    latencyBadge.innerText = `${data.latency_ms || 0} ms`;
    resultBox.innerText = JSON.stringify(data.result !== undefined ? data.result : data, null, 2);
  } catch (err) {
    resultContainer.style.display = 'block';
    latencyBadge.innerText = 'Error';
    resultBox.innerText = 'Error executing tool: ' + err.message;
  } finally {
    runBtn.disabled = false;
    runBtn.innerHTML = '<span>🚀 Execute Tool in Sandbox</span>';
  }
}

