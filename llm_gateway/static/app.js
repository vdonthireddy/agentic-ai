async function sendChatMessage() {
  const input = document.getElementById('chat-input-text');
  const message = input.value.trim();
  if (!message) return;

  const model = document.getElementById('chat-model-select').value;
  const skill = document.getElementById('chat-skill-select').value;
  const sendBtn = document.getElementById('chat-send-btn');
  const container = document.getElementById('chat-messages-container');

  const welcome = container.querySelector('.chat-welcome');
  if (welcome) welcome.remove();

  // 1. Render User Message
  renderUserMessage(message);
  input.value = '';
  input.focus();

  // 2. Render Loading Bubble
  const loadingBubbleId = `loading_${Date.now()}`;
  renderBotLoading(loadingBubbleId);
  container.scrollTop = container.scrollHeight;

  sendBtn.disabled = true;

  try {
    const res = await fetch('/api/chat', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        message: message,
        model: model,
        skill_name: skill,
        session_id: activeSessionId
      })
    });

    const data = await res.json();
    if (!res.ok) throw new Error(data.message || data.detail || 'Chat request failed');

    const loadingElem = document.getElementById(loadingBubbleId);
    if (loadingElem) loadingElem.remove();

    // 3. Render Assistant Response
    renderBotResponse(data);
    container.scrollTop = container.scrollHeight;

    // Update Turn Telemetry
    if (data.tokens) {
      document.getElementById('last-prompt-tokens').innerText = data.tokens.prompt_tokens || 0;
      document.getElementById('last-completion-tokens').innerText = data.tokens.completion_tokens || 0;
    }
    document.getElementById('last-tools-count').innerText = (data.tool_calls || []).length;

    setTimeout(fetchData, 400);

  } catch (err) {
    const loadingElem = document.getElementById(loadingBubbleId);
    if (loadingElem) loadingElem.remove();

    renderBotError(err.message);
    container.scrollTop = container.scrollHeight;
  } finally {
    sendBtn.disabled = false;
  }
}

function renderUserMessage(text) {
  const container = document.getElementById('chat-messages-container');
  const div = document.createElement('div');
  div.className = 'chat-message message-user';
  div.innerHTML = `
    <div class="message-bubble">
      <div class="message-content">${escapeHtml(text)}</div>
    </div>
  `;
  container.appendChild(div);
  chatHistory.push({ role: 'user', content: text, timestamp: new Date().toISOString() });
}

