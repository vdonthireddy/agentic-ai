function renderModelsChart() {
  const container = document.getElementById('models-distribution-container');
  const models = gatewayStats.models_usage || {};
  const total = Object.values(models).reduce((a, b) => a + b, 0);

  if (total === 0) {
    container.innerHTML = '<div class="text-muted text-center py-6">No inference calls recorded yet.</div>';
    return;
  }

  let html = '';
  for (const [model, count] of Object.entries(models)) {
    const pct = ((count / total) * 100).toFixed(1);
    html += `
      <div class="model-stat-row">
        <div class="flex-between mb-1">
          <span class="font-mono text-sm"><code>${escapeHtml(model)}</code></span>
          <span class="text-sm"><strong>${count} calls</strong> (${pct}%)</span>
        </div>
        <div class="progress-track"><div class="progress-fill" style="width:${pct}%;"></div></div>
      </div>
    `;
  }
  container.innerHTML = html;
}

function populateModelSelectors(defaultModel) {
  const selects = [
    document.getElementById('chat-model-select'),
    document.getElementById('log-model-filter'),
    document.getElementById('eval-model-select')
  ];

  if (availableModels.length === 0) return;

  const def = defaultModel || window.configuredDefaultModel || (availableModels[0] ? availableModels[0].id : '');

  const groups = {};
  for (const m of availableModels) {
    let groupName = 'Cloud Providers';
    if (m.provider === 'ollama' || m.is_local) groupName = 'Local Ollama';
    else if (m.provider === 'openai') groupName = 'OpenAI';
    else if (m.provider === 'anthropic') groupName = 'Anthropic Claude';
    else if (m.provider === 'gemini') groupName = 'Google Gemini';
    else if (m.provider === 'groq') groupName = 'Groq Cloud';
    else if (m.provider === 'deepseek') groupName = 'DeepSeek';
    else if (m.provider === 'mistral') groupName = 'Mistral AI';

    if (!groups[groupName]) groups[groupName] = [];
    groups[groupName].push(m);
  }

  for (const sel of selects) {
    if (!sel) continue;
    const cur = sel.dataset.userSelected ? sel.value : null;
    let opts = sel.id === 'log-model-filter' ? '<option value="">All Models</option>' : '';

    for (const [groupLabel, models] of Object.entries(groups)) {
      opts += `<optgroup label="${groupLabel}">`;
      for (const m of models) {
        const isDef = m.id === def;
        const displayName = m.name && m.name !== m.id ? `${m.name} (${m.id})` : m.id;
        opts += `<option value="${m.id}" ${isDef ? 'selected' : ''}>${displayName}${isDef ? ' ⭐' : ''}</option>`;
      }
      opts += `</optgroup>`;
    }

    sel.innerHTML = opts;
    if (cur) sel.value = cur;
    else if (sel.id !== 'log-model-filter' && def) sel.value = def;

    if (!sel.dataset.listenerAttached) {
      sel.addEventListener('change', () => { sel.dataset.userSelected = 'true'; });
      sel.dataset.listenerAttached = 'true';
    }
  }

  const activeModelDisplay = document.getElementById('active-model-display');
  if (activeModelDisplay) activeModelDisplay.innerText = def;
}

