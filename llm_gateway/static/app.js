async function submitCreateCustomSkill() {
  const id = document.getElementById('new-skill-id').value.trim();
  const name = document.getElementById('new-skill-name').value.trim();
  const desc = document.getElementById('new-skill-desc').value.trim();
  const prompt = document.getElementById('new-skill-prompt').value.trim();

  if (!id || !name || !prompt) {
    alert('Please fill out Skill Identifier, Name, and Persona Prompt.');
    return;
  }

  try {
    const res = await fetch('/api/skills/custom', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        id: id,
        name: name,
        description: desc,
        system_prompt: prompt,
        category: 'Custom User Skills'
      })
    });
    if (res.ok) {
      closeCreateSkillModal();
      fetchSkillsHub();
    } else {
      const err = await res.json();
      alert('Failed: ' + (err.detail || err.message));
    }
  } catch (e) {
    alert('Error: ' + e.message);
  }
}

