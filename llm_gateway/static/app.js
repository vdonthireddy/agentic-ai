// Tab Switching
function switchTab(tabId) {
  currentTab = tabId;
  document.querySelectorAll('.tab-pane').forEach(el => el.classList.remove('active'));
  document.querySelectorAll('.nav-btn').forEach(el => el.classList.remove('active'));
  
  const targetPane = document.getElementById(`tab-${tabId}`);
  const targetNav = document.getElementById(`nav-${tabId}`);
  if (targetPane) targetPane.classList.add('active');
  if (targetNav) targetNav.classList.add('active');

  const titleMap = {
    chat: { title: 'AI Agent Chatbot', subtitle: 'Interactive ReAct Agent with Everyday Tools, Domain Skills & Multi-Provider Gateway' },
    tools: { title: 'MCP Tools & Sandbox', subtitle: 'Directly inspect, parameterize, and execute Model Context Protocol tools in a live sandbox' },
    skills: { title: 'Domain Skills Hub', subtitle: 'Explore, customize, and create specialized agent personas with custom prompt injections' },
    workspace: { title: 'Workspace File Explorer', subtitle: 'Manage persistent files generated by agents, tools, itineraries, and shopping lists' },
    overview: { title: 'Telemetry & Observatory', subtitle: 'Real-time LLM inference audit trails, token telemetry & agent interactions' },
    logs: { title: 'Interaction Audit Logs', subtitle: 'Searchable historical prompts, responses, tool calls, and caller contexts' },
    evals: { title: 'Evals & Benchmarks', subtitle: 'Evaluate tool accuracy, skill adherence, and execution correctness across models' },
    settings: { title: 'Settings & Diagnostics', subtitle: 'Manage multi-provider API keys, Ollama base URLs, transport mode, and monitor host system metrics' }
  };

  const meta = titleMap[tabId] || { title: 'Unified Studio', subtitle: '' };
  document.getElementById('page-title').innerText = meta.title;
  document.getElementById('page-subtitle').innerText = meta.subtitle;

  if (tabId === 'tools') fetchToolsCatalog();
  if (tabId === 'skills') fetchSkillsHub();
  if (tabId === 'workspace') fetchWorkspaceFiles();
  if (tabId === 'evals') fetchEvalRegistries();
  if (tabId === 'settings') {
    fetchGatewayConfig();
    fetchSystemTelemetryUI();
  }
}

